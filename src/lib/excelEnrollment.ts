export async function parseEnrollmentFile(params: {
  file: File;
  classes: SchoolClass[];
  existingPupils: Pupil[];
  schoolCode?: string;
  defaultClassId?: string;
}): Promise<EnrollmentParseResult> {
  const isCsv = params.file.name.toLowerCase().endsWith('.csv');
  const rawRows: unknown[][] = isCsv
    ? parseCsvRows(await params.file.text())
    : await readSheet(params.file);

  if (!rawRows || rawRows.length < 2) {
    throw new Error('The uploaded file appears to be empty or has no pupil data rows.');
  }

  // Locate header row within the first 6 rows
  let headerRowIdx = 0;
  let bestScore = -1;
  const maxScan = Math.min(6, rawRows.length);
  for (let i = 0; i < maxScan; i++) {
    const normalized = (rawRows[i] || []).map(normalizeHeader);
    let score = 0;
    if (normalized.some((h) => h.includes('first name') || h.includes('full name') || h.includes('pupil name') || h === 'name')) score += 3;
    if (normalized.some((h) => h.includes('last name') || h.includes('surname'))) score += 2;
    if (normalized.some((h) => h.includes('gender') || h === 'sex')) score += 2;
    if (normalized.some((h) => h.includes('class') || h.includes('grade') || h.includes('level'))) score += 2;
    if (normalized.some((h) => h.includes('admission') || h.includes('reg'))) score += 1;
    if (score > bestScore) {
      bestScore = score;
      headerRowIdx = i;
    }
  }

  const headerCells = (rawRows[headerRowIdx] || []).map(cleanCell);
  const normalizedHeaders = headerCells.map(normalizeHeader);

  const idxAdmission = findColumnIndex(normalizedHeaders, [
    'admission number',
    'admission no',
    'reg no',
    'registration number',
    'registration no',
    'student id',
    'pupil id',
    'admission',
  ]);
  const idxFirstName = findColumnIndex(normalizedHeaders, ['first name', 'firstname', 'given name']);
  const idxLastName = findColumnIndex(normalizedHeaders, ['last name', 'lastname', 'surname', 'family name']);
  const idxOtherNames = findColumnIndex(normalizedHeaders, ['other names', 'other name', 'middle name', 'middlename']);
  const idxFullName = findColumnIndex(normalizedHeaders, ['full name', 'pupil name', 'student name', 'learner name', 'name']);
  const idxGender = findColumnIndex(normalizedHeaders, ['gender', 'sex']);
  const idxDob = findColumnIndex(normalizedHeaders, ['date of birth', 'dob', 'birth date', 'birthdate']);
  const idxClass = findColumnIndex(normalizedHeaders, ['class', 'class name', 'grade', 'level', 'form']);
  const idxGuardianName = findColumnIndex(normalizedHeaders, ['guardian name', 'parent name', 'guardian', 'parent']);
  const idxGuardianPhone = findColumnIndex(normalizedHeaders, [
    'guardian phone',
    'parent phone',
    'guardian contact',
    'phone number',
    'phone',
    'telephone',
    'contact',
  ]);
  const idxStatus = findColumnIndex(normalizedHeaders, ['enrollment status', 'status']);
  const idxParentPassword = findColumnIndex(normalizedHeaders, [
    'parent portal password',
    'parent password',
    'portal password',
    'password',
  ]);

  if (idxFirstName < 0 && idxFullName < 0) {
    throw new Error(
      'Could not find a "First Name" or "Full Name" column. Please download and use the system-generated Excel Enrollment Sheet.'
    );
  }

  const classLookup = buildClassLookup(params.classes);
  const defaultClass =
    params.defaultClassId && params.defaultClassId !== 'NONE'
      ? params.classes.find((c) => c.id === params.defaultClassId) || null
      : null;

  const existingByAdmission = new Map<string, Pupil>();
  for (const p of params.existingPupils) {
    const key = normalizeAdmissionKey(p.admissionNumber);
    if (key) existingByAdmission.set(key, p);
  }

  const seqGen = computeNextAdmissionPrefixAndStart(params.schoolCode, params.existingPupils);
  const seenAdmissionsInFile = new Map<string, number>();
  const seenIdentitiesInFile: Array<PupilDuplicateCandidate & { rowNumber: number }> = [];
  const seenMatchedPupilIdsInFile = new Map<string, number>();

  const rows: ParsedEnrollmentRow[] = [];
  let totalRowsScanned = 0;

  for (let i = headerRowIdx + 1; i < rawRows.length; i++) {
    const raw = rawRows[i] || [];
    const excelRowNum = i + 1;

    const rawAdmission = idxAdmission >= 0 ? cleanCell(raw[idxAdmission]) : '';
    let firstName = idxFirstName >= 0 ? cleanCell(raw[idxFirstName]) : '';
    let lastName = idxLastName >= 0 ? cleanCell(raw[idxLastName]) : '';
    let otherNames = idxOtherNames >= 0 ? cleanCell(raw[idxOtherNames]) : '';
    const rawFullName = idxFullName >= 0 ? cleanCell(raw[idxFullName]) : '';
    const rawGender = idxGender >= 0 ? cleanCell(raw[idxGender]) : '';
    const rawDobVal = idxDob >= 0 ? raw[idxDob] : '';
    const rawClass = idxClass >= 0 ? cleanCell(raw[idxClass]) : '';
    const guardianName = idxGuardianName >= 0 ? cleanCell(raw[idxGuardianName]) : '';
    const guardianPhone = idxGuardianPhone >= 0 ? cleanCell(raw[idxGuardianPhone]) : '';
    const rawStatus = idxStatus >= 0 ? cleanCell(raw[idxStatus]) : '';
    const parentPassword = idxParentPassword >= 0 ? cleanCell(raw[idxParentPassword]) : '';

    // Skip completely empty rows OR untouched pre-filled blank template rows
    const hasIdentityInput = Boolean(
      rawAdmission || firstName || lastName || otherNames || rawFullName || rawGender || guardianName || guardianPhone
    );
    if (!hasIdentityInput) {
      continue;
    }

    totalRowsScanned++;

    if (!firstName && !lastName && rawFullName) {
      const split = splitFullName(rawFullName);
      firstName = split.firstName;
      otherNames = otherNames || split.otherNames;
      lastName = split.lastName;
    } else if (firstName && !lastName && firstName.includes(' ')) {
      const split = splitFullName(firstName);
      firstName = split.firstName;
      otherNames = otherNames || split.otherNames;
      lastName = split.lastName;
    }

    const fullName = [firstName, otherNames, lastName].filter(Boolean).join(' ');
    const errors: string[] = [];
    const warnings: string[] = [];

    if (!firstName) errors.push('Missing First Name');
    if (!lastName) errors.push('Missing Last Name');

    const gender = normalizeGender(rawGender);
    if (!gender) {
      errors.push(rawGender ? `Invalid Gender "${rawGender}" (use Male or Female)` : 'Missing Gender (Male/Female)');
    }

    let matchedClass: SchoolClass | null = null;
    if (rawClass) {
      matchedClass = classLookup.get(compactClassKey(rawClass)) || null;
      if (!matchedClass) {
        errors.push(`Unknown Class "${rawClass}" (check Valid Classes tab)`);
      }
    } else if (defaultClass) {
      matchedClass = defaultClass;
      warnings.push(`Class defaulted to ${defaultClass.name}`);
    } else {
      errors.push('Missing Class');
    }

    const dobResult = normalizeDateOfBirth(rawDobVal);
    if (dobResult.warning) warnings.push(dobResult.warning);

    if (parentPassword && parentPassword.length < 4) {
      errors.push('Parent Portal Password must be at least 4 characters');
    }

    let admissionNumber = rawAdmission;
    let autoGeneratedAdmission = false;
    if (!admissionNumber) {
      let candidate = `${seqGen.prefix}-${seqGen.year}-${seqGen.nextSeq}`;
      while (seqGen.usedNumbers.has(candidate.toUpperCase())) {
        seqGen.nextSeq++;
        candidate = `${seqGen.prefix}-${seqGen.year}-${seqGen.nextSeq}`;
      }
      seqGen.nextSeq++;
      seqGen.usedNumbers.add(candidate.toUpperCase());
      admissionNumber = candidate;
      autoGeneratedAdmission = true;
    }

    const normalizedAdmKey = normalizeAdmissionKey(admissionNumber);
    const prevSeenRow = seenAdmissionsInFile.get(normalizedAdmKey);
    if (prevSeenRow !== undefined) {
      errors.push(`Duplicate Admission Number in Excel file (already on row ${prevSeenRow})`);
    } else {
      seenAdmissionsInFile.set(normalizedAdmKey, excelRowNum);
    }

    const identityCandidate: PupilDuplicateCandidate = {
      admissionNumber: rawAdmission,
      firstName,
      otherNames,
      lastName,
      fullName,
      gender: gender || undefined,
      dateOfBirth: dobResult.normalized,
      currentClassId: matchedClass?.id || '',
      currentClassName: matchedClass?.name || rawClass || '',
      guardianPhone,
    };

    const intraIdentityDup = findDuplicatePupil(seenIdentitiesInFile, {
      ...identityCandidate,
      admissionNumber: '',
    });
    if (intraIdentityDup) {
      errors.push(
        `Duplicate pupil in Excel file (matches row #${intraIdentityDup.matchedPupil.rowNumber})`
      );
    } else if (firstName && lastName && gender) {
      seenIdentitiesInFile.push({
        ...identityCandidate,
        rowNumber: excelRowNum,
      });
    }

    const existingByAdm = rawAdmission ? existingByAdmission.get(normalizedAdmKey) || null : null;
    let existing: Pupil | null = existingByAdm;
    let matchedBy: 'admission' | 'identity' | null = existingByAdm ? 'admission' : null;

    if (existingByAdm) {
      const conflictingIdentity = findDuplicatePupil(
        params.existingPupils,
        { ...identityCandidate, admissionNumber: '' },
        existingByAdm.id
      );
      if (conflictingIdentity) {
        errors.push(
          `Details conflict with another enrolled pupil ${conflictingIdentity.matchedPupil.fullName} (${conflictingIdentity.matchedPupil.admissionNumber})`
        );
      }
    } else {
      const existingIdentityDup = findDuplicatePupil(params.existingPupils, identityCandidate);
      if (existingIdentityDup) {
        existing = existingIdentityDup.matchedPupil;
        matchedBy = 'identity';
        warnings.push(
          `Already enrolled as "${existing.fullName}" (${existing.admissionNumber})`
        );
      }
    }

    if (existing) {
      const prevMatchedRow = seenMatchedPupilIdsInFile.get(existing.id);
      if (prevMatchedRow !== undefined) {
        errors.push(
          `Duplicate match for existing pupil "${existing.fullName}" (${existing.admissionNumber}) — already listed on row #${prevMatchedRow}`
        );
      } else {
        seenMatchedPupilIdsInFile.set(existing.id, excelRowNum);
      }
    }

    rows.push({
      rowNumber: excelRowNum,
      admissionNumber,
      autoGeneratedAdmission,
      firstName,
      lastName,
      otherNames,
      fullName: fullName || '(Unnamed Pupil)',
      gender,
      rawGender,
      dateOfBirth: dobResult.normalized,
      classId: matchedClass?.id || null,
      className: matchedClass?.name || rawClass || '—',
      rawClass,
      guardianName,
      guardianPhone,
      enrollmentStatus: normalizeEnrollmentStatus(rawStatus),
      parentPassword,
      existingPupilId: existing?.id || null,
      existingPupilName: existing?.fullName || null,
      existingPupilAdmissionNumber: existing?.admissionNumber || null,
      matchedBy,
      errors,
      warnings,
    });
  }

  return {
    fileName: params.file.name,
    totalRowsScanned,
    rows,
    detectedHeaders: headerCells.filter(Boolean),
  };
}
